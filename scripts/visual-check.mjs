import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', err => errors.push(err.message));
const target = process.env.CHECK_URL || 'http://127.0.0.1:5190';
const dir = path.resolve('test-results/visual');
await mkdir(dir, { recursive: true });
await page.goto(target);
await page.screenshot({ path: path.join(dir, 'welcome-desktop.png'), fullPage: true });
await page.getByTestId('import-input').setInputFiles('.test-data/mixed-12.pdf');
await page.locator('#loading').waitFor({ state: 'hidden' });
await page.waitForFunction(() => [...document.querySelectorAll('.pdf-reader-ready img')].some(i => i.complete && i.naturalWidth > 0));
await page.screenshot({ path: path.join(dir, 'reader-cover.png') });
await page.getByTestId('page-input').fill('4'); await page.getByTestId('page-input').press('Enter');
await page.waitForTimeout(1000);
await page.screenshot({ path: path.join(dir, 'reader-spread.png') });
await page.getByTestId('thumbnails-toggle').click();
await page.waitForTimeout(1000);
await page.screenshot({ path: path.join(dir, 'reader-thumbnails.png') });
await page.setViewportSize({ width: 390, height: 844 });
await page.locator('#thumbnails-close').click();
await page.waitForTimeout(800);
await page.screenshot({ path: path.join(dir, 'reader-mobile.png') });
await page.getByTestId('close-reader').click();
await page.screenshot({ path: path.join(dir, 'welcome-mobile.png'), fullPage: true });
console.log(JSON.stringify({ errors, screenshots: dir }, null, 2));
await browser.close();
